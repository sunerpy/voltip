package dev.voltip.mobile

import android.app.Activity
import android.os.Build
import app.tauri.annotation.Command
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

/**
 * Where updates come from (docs/dictation.md §20.9): the package that installed this app.
 * `com.android.vending` is Google Play, which updates the app itself; anything else (the browser or
 * file manager that opened the APK of a GitHub release, or `adb`) means the app looks for new
 * releases on GitHub. The Rust side (`src/update.rs`) asks once at startup. Not generated by
 * `cargo tauri android init`: keep this file when regenerating the project.
 */
@TauriPlugin
class UpdatePlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun installSource(invoke: Invoke) {
        val packages = activity.packageManager
        val installer = try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                packages.getInstallSourceInfo(activity.packageName).installingPackageName
            } else {
                @Suppress("DEPRECATION")
                packages.getInstallerPackageName(activity.packageName)
            }
        } catch (e: Exception) {
            null
        }
        val ret = JSObject()
        // No installer on record (adb, a system image): the key stays out and reads as none.
        if (installer != null) ret.put("installer", installer)
        invoke.resolve(ret)
    }
}
