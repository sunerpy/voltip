package dev.voltip.mobile

import android.app.Activity
import android.content.Context
import android.net.wifi.WifiManager
import app.tauri.annotation.Command
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.Plugin

/**
 * Holds a Wi-Fi multicast lock for LAN discovery (docs/pairing.md 「局域网发现」): without it the
 * driver drops the mDNS packets `_voltip._tcp` rides on. The Rust side (`src/multicast.rs`) calls
 * `acquire` at start and `acquire` / `release` as the LAN discovery switch changes. Needs
 * CHANGE_WIFI_MULTICAST_STATE (a normal permission, no prompt). Not generated by
 * `cargo tauri android init`: keep this file when regenerating the project.
 */
@TauriPlugin
class MulticastPlugin(private val activity: Activity) : Plugin(activity) {
    private var lock: WifiManager.MulticastLock? = null

    @Command
    fun acquire(invoke: Invoke) {
        val wifi = activity.applicationContext.getSystemService(Context.WIFI_SERVICE) as WifiManager
        val held = lock ?: wifi.createMulticastLock("voltip-lan-discovery").also {
            it.setReferenceCounted(false)
            lock = it
        }
        if (!held.isHeld) held.acquire()
        invoke.resolve()
    }

    @Command
    fun release(invoke: Invoke) {
        lock?.let { if (it.isHeld) it.release() }
        invoke.resolve()
    }
}
