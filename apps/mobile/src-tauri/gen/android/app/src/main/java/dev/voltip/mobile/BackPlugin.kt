package dev.voltip.mobile

import android.app.Activity
import android.os.SystemClock
import android.util.Log
import androidx.activity.OnBackPressedCallback
import androidx.appcompat.app.AppCompatActivity
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

@InvokeArg
class BackReleaseArgs {
    var ms: Long = 0
}

/**
 * Android's back (docs/dictation.md §20.10): while the front end listens (`registerListener`
 * for `back`, `apps/mobile/src/app/back.ts`), every back goes to it, and it goes up a level;
 * `release` lets the backs of the next `ms` through to the system, which leaves the app (the
 * second of two backs at 说话).
 *
 * Every instance of MainActivity gets its own callback ([attach], from `MainActivity.onCreate`).
 * Android recreates the activity when an overlay changes (the navigation mode, the wallpaper's
 * colours), and when the display or font size does; Tauri's own back handler (its AppPlugin) is
 * added to the first instance alone, so after a recreation every back left the app (the
 * android-device CI job, 2026-10-03). The listeners and the release live in the plugin, which
 * outlives the activities. Not generated by `cargo tauri android init`: keep this file when
 * regenerating the project.
 */
@TauriPlugin
class BackPlugin(activity: Activity) : Plugin(activity) {
    @Volatile
    private var releasedUntil = 0L

    init {
        current = this
    }

    @Command
    fun release(invoke: Invoke) {
        val args = invoke.parseArgs(BackReleaseArgs::class.java)
        releasedUntil = SystemClock.uptimeMillis() + args.ms
        Log.i(TAG, "release ${args.ms} ms")
        invoke.resolve()
    }

    /** True when this back went to the front end, false when the system should take it. */
    private fun deliver(): Boolean {
        if (!hasListener(EVENT) || SystemClock.uptimeMillis() < releasedUntil) return false
        trigger(EVENT, JSObject())
        return true
    }

    companion object {
        private const val TAG = "VoltipBack"
        private const val EVENT = "back"

        @Volatile
        private var current: BackPlugin? = null

        /** Takes the backs of `activity`; call it from every `onCreate`. */
        fun attach(activity: AppCompatActivity) {
            val callback = object : OnBackPressedCallback(true) {
                override fun handleOnBackPressed() {
                    if (current?.deliver() == true) {
                        Log.i(TAG, "back to the page")
                        return
                    }
                    Log.i(TAG, "back to the system")
                    // The system's own back: with this callback off, the dispatcher falls through
                    // to the activity's default, which leaves the app.
                    isEnabled = false
                    activity.onBackPressedDispatcher.onBackPressed()
                    isEnabled = true
                }
            }
            activity.onBackPressedDispatcher.addCallback(activity, callback)
            Log.i(TAG, "attached to activity ${System.identityHashCode(activity)}")
        }
    }
}
