package dev.voltip.mobile

import android.app.Activity
import android.content.Intent
import androidx.core.content.FileProvider
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.Plugin
import java.io.File

@InvokeArg
class ShareTextArgs {
    var text: String = ""
}

@InvokeArg
class ShareFileArgs {
    var name: String = ""
    var text: String = ""
    var mime: String = "text/plain"
}

/**
 * 「分享」 (docs/dictation.md §20.7): hands a result to another app through the system share sheet
 * (`ACTION_SEND`). The Rust side (`src/share.rs`) calls `shareText` with plain text, and
 * `shareFile` with a history export (subtitles or text, §22), which goes as a file: the share
 * target reads it from the app's cache through the manifest's FileProvider (`res/xml/file_paths.xml`
 * lists the cache). Not generated by `cargo tauri android init`: keep this file when regenerating
 * the project.
 */
@TauriPlugin
class SharePlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun shareText(invoke: Invoke) {
        val args = invoke.parseArgs(ShareTextArgs::class.java)
        val send = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, args.text)
        }
        activity.startActivity(Intent.createChooser(send, null))
        invoke.resolve()
    }

    @Command
    fun shareFile(invoke: Invoke) {
        val args = invoke.parseArgs(ShareFileArgs::class.java)
        try {
            // One export at a time: the previous one's target has read it by now.
            val dir = File(activity.cacheDir, "exports").apply { mkdirs() }
            dir.listFiles()?.forEach { it.delete() }
            val file = File(dir, File(args.name).name)
            file.writeText(args.text, Charsets.UTF_8)
            val uri = FileProvider.getUriForFile(activity, "${activity.packageName}.fileprovider", file)
            val send = Intent(Intent.ACTION_SEND).apply {
                type = args.mime
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, file.name)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            activity.startActivity(Intent.createChooser(send, null))
            invoke.resolve()
        } catch (e: Exception) {
            invoke.reject(e.message ?: e.javaClass.simpleName)
        }
    }
}
