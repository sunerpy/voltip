package dev.voltip.mobile

import android.app.Activity
import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

@InvokeArg
class WriteTextArgs {
    var text: String = ""
}

/**
 * The phone's clipboard (docs/dictation.md §20.6, §20.7): read for 「发送剪贴板」 and written with
 * the result of a take the phone recognised itself. Android 10+ lets only the app in front read
 * it, which Voltip is while the user taps the button; the Rust side (`src/clipboard.rs`) calls
 * `readText` and `writeText`. Not generated by `cargo tauri android init`: keep this file when
 * regenerating the project.
 */
@TauriPlugin
class PhoneClipboardPlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun readText(invoke: Invoke) {
        val manager = activity.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        val clip = manager.primaryClip
        val text = if (clip != null && clip.itemCount > 0) clip.getItemAt(0).coerceToText(activity)?.toString() else null
        val ret = JSObject()
        ret.put("text", text)
        invoke.resolve(ret)
    }

    @Command
    fun writeText(invoke: Invoke) {
        val args = invoke.parseArgs(WriteTextArgs::class.java)
        val manager = activity.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        manager.setPrimaryClip(ClipData.newPlainText("Voltip", args.text))
        invoke.resolve()
    }
}
